def normalize_text(name: str) -> str:
    """基础文本规范化"""
    # 用字统一
    for old, new in CHAR_REPLACEMENTS.items():
        name = name.replace(old, new)

    # 移除括号备注、疑问标记、补充说明
    for pattern in REMOVE_PATTERNS:
        name = re.sub(pattern, "", name)

    # 去除首尾空白
    name = name.strip()

    # 统一全角/半角空格
    name = re.sub(r"\s+", "", name)

    return name


def apply_location_rules(name: str) -> str:
    """应用解剖方位归一化规则"""
    for pattern, standard in LOCATION_NORMALIZATION.items():
        if re.match(pattern, name):
            return standard
    return name


def apply_treatment_rules(name: str) -> str:
    """应用治疗状态归一化规则"""
    for pattern, standard in TREATMENT_STATUS_PATTERNS:
        if re.match(pattern, name):
            return standard
    return name


def standardize_disease(name: str) -> tuple[str, str]:
    """
    标准化单一疾病名称。
    返回: (standard_name, rule)
    """
    original = name

    # 步骤1: 基础文本规范化
    name = normalize_text(name)
    if name != original:
        rule = "基础规范化"
    else:
        rule = "原始名称"

    # 步骤2: 治疗状态归一化
    new_name = apply_treatment_rules(name)
    if new_name != name:
        name = new_name
        rule = "治疗状态归一"

    # 步骤3: 解剖方位归一化
    new_name = apply_location_rules(name)
    if new_name != name:
        name = new_name
        rule = "解剖方位归一"

    # 步骤4: 同义词/标准名映射
    if name in DISEASE_SYNONYMS:
        mapped = DISEASE_SYNONYMS[name]
        if mapped != name:
            rule = "同义词映射"
        name = mapped

    # 步骤5: 术后状态统一
    if name.endswith("术后") and name not in ("术后",):
        # 保持特定术后状态，如 "子宫切除术后状态" 已在同义词表中
        pass

    # 步骤6: 若仍为空或与原始差异大，标记待复核
    if not name:
        name = original
        rule = "待人工复核（空值）"

    return name, rule


def parse_western_diseases(file_path: Path) -> list[dict]:
    """解析西医病症文件"""
    diseases = []
    with open(file_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split(" | ")
            if len(parts) >= 3:
                diseases.append({
                    "original_name": parts[0],
                    "source": parts[1],
                    "frequency": int(parts[2]),
                })
    return diseases


def main():
    output_dir = get_output_dir()
    input_file = output_dir / "知识图谱_病症_西医.txt"

    print(f"[读取] {input_file.name}")
    diseases = parse_western_diseases(input_file)
    print(f"[信息] 共读取 {len(diseases)} 条西医病症")

    # 标准化映射
    mapping_rows = []
    standard_freq = defaultdict(int)
    rule_counts = defaultdict(int)
    review_list = []

    for d in diseases:
        standard_name, rule = standardize_disease(d["original_name"])
        mapping_rows.append({
            "original_name": d["original_name"],
            "standard_name": standard_name,
            "rule": rule,
            "frequency": d["frequency"],
            "source": d["source"],
        })
        standard_freq[standard_name] += d["frequency"]
        rule_counts[rule] += 1
        if rule in ("待人工复核（空值）",):
            review_list.append(d["original_name"])

    # 输出映射表 TSV
    mapping_file = output_dir / "西医病症标准化映射.tsv"
    with open(mapping_file, "w", encoding="utf-8") as f:
        f.write("原始名称\t标准名称\t映射规则\t频次\t来源\n")
        for row in mapping_rows:
            f.write(f"{row['original_name']}\t{row['standard_name']}\t{row['rule']}\t{row['frequency']}\t{row['source']}\n")

    # 输出标准化后病症列表（按频次降序）
    standard_list_file = output_dir / "西医病症标准化列表.txt"
    sorted_standards = sorted(standard_freq.items(), key=lambda x: (-x[1], x[0]))
    with open(standard_list_file, "w", encoding="utf-8") as f:
        f.write(f"# 西医病症标准化列表（共 {len(sorted_standards)} 条唯一标准病症）\n")
        f.write("# 格式：标准名称 | 总频次\n")
        for name, freq in sorted_standards:
            f.write(f"{name} | {freq}\n")

    # 输出统计摘要
    summary_file = output_dir / "西医病症标准化统计.md"
    summary = f"""# 西医病症标准化统计

## 总体统计

| 指标 | 数值 |
|------|------|
| 原始病症条目数 | {len(diseases)} |
| 标准化后唯一病症数 | {len(standard_freq)} |
| 合并/归一减少数 | {len(diseases) - len(standard_freq)} |
| 减少比例 | {((len(diseases) - len(standard_freq)) / len(diseases) * 100):.1f}% |

## 映射规则分布

| 映射规则 | 原始条目数 |
|---------|-----------|
"""
    for rule, count in sorted(rule_counts.items(), key=lambda x: -x[1]):
        summary += f"| {rule} | {count} |\n"

    summary += f"""
## 输出文件

- `{mapping_file.name}`：原始名称 → 标准名称的完整映射表。
- `{standard_list_file.name}`：标准化后的唯一病症列表及总频次。

## 说明

- 标准化规则主要覆盖：**同义词归一**、**解剖方位归并**、**治疗状态归一**、**拼写/用字统一**。
- 对于组合诊断（如 `"心律失常 窦性心动过缓 完全性左束支传导阻滞"`）等复杂条目，
  当前未拆分，保留了原始完整名称；如需进一步拆分，可补充组合诊断拆分规则。
- 部分低频、复杂或包含多重信息的条目建议人工复核。
"""
    summary_file.write_text(summary, encoding="utf-8")

    print(f"[输出] {mapping_file.name}")
    print(f"[输出] {standard_list_file.name}")
    print(f"[输出] {summary_file.name}")
    print("=" * 60)
    print(f"[结果] 原始病症条目数：{len(diseases)}")
    print(f"[结果] 标准化后唯一病症数：{len(standard_freq)}")
    print(f"[结果] 合并减少数：{len(diseases) - len(standard_freq)} ({((len(diseases) - len(standard_freq)) / len(diseases) * 100):.1f}%)")
    print("=" * 60)


